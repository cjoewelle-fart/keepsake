// Writes video/launch-film/assets/brand.js from src/brand.ts, so the films take the product name,
// tagline and web address from the same single setting as the app. Run before every render:
//   node video/sync-brand.mjs
import { writeFileSync } from 'node:fs'
import { APP_NAME, TAGLINE, SITE_URL } from '../src/brand.ts'

const url = SITE_URL.replace(/^https?:\/\//, '').replace(/\/$/, '')
const out = `// Generated by video/sync-brand.mjs from src/brand.ts. Don't edit: change src/brand.ts and re-run.
window.BRAND = {
  appName: ${JSON.stringify(APP_NAME)},
  tagline: ${JSON.stringify(TAGLINE)},
  freeLine: 'Free, and it runs in your browser.',
  // Empty until the domain is bought (D42): the end card then leaves the address line out.
  siteUrl: ${JSON.stringify(url)},
};
`
writeFileSync(new URL('./launch-film/assets/brand.js', import.meta.url), out)
console.log(`brand.js: ${APP_NAME}, address ${url || '(none yet)'}`)
